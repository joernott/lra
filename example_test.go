package lra_test

import (
	"context"
	"errors"
	"fmt"
	"log"
	"net/http"
	"time"

	"github.com/joernott/lra"
)

func ExampleNewConnection() {
	hl := lra.HeaderList{"Content-Type": "application/json"}
	connection, err := lra.NewConnection(
		true,                            // use SSL
		"elasticsearch.example.com",     // server name or IP address
		9200,                            // port
		"",                              // no additional base endpoint
		"admin",                         // user name
		"1234",                          // password
		false,                           // we use a certificate generated by the elasticsearch CA
		"http://proxy.example.com:3128", // we use a proxy
		false,                           // it is not a socks5 proxy
		hl,                              // we want to pass those headers
		30*time.Second,                  // request timeout, 0 means lra.DefaultTimeout
	)
	if err != nil {
		log.Fatal(err)
	}

	var status map[string]any
	if err := connection.GetJSON("/_cluster/health", &status); err != nil {
		log.Fatal(err)
	}
	fmt.Println(status["status"])
}

func ExampleConnection_GetJSONContext() {
	connection, err := lra.NewConnection(true, "elasticsearch.example.com", 9200, "", "", "", true, "", false, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	var status map[string]any
	err = connection.GetJSONContext(ctx, "/_cluster/health", &status)
	if se, ok := errors.AsType[*lra.StatusError](err); ok && se.StatusCode == http.StatusNotFound {
		fmt.Println("not found")
		return
	}
	if err != nil {
		log.Fatal(err)
	}
	fmt.Println(status["status"])
}
